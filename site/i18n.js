// ?lang=pt in a link wins, then what the visitor picked before, then the browser's language
export function startingLang(search = location.search, saved = null, browser = navigator.language) {
  const asked = new URLSearchParams(search).get('lang');
  if (asked === 'pt' || asked === 'en') return asked;
  if (saved === 'pt' || saved === 'en') return saved;
  return browser?.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}
